"""Работа с временем из БД: пометка UTC у «наивных» значений.

Зачем: часть колонок в БД — ``timestamp without time zone`` (например, время
сообщения), а сервер живёт в UTC. Такое значение уходит в API БЕЗ смещения
(``2026-09-10T18:59:11.428769``), а браузер и любой другой клиент по спецификации
ISO 8601 трактует строку без смещения как ЛОКАЛЬНОЕ время. В UTC+3 сообщение
показывалось на три часа раньше, чем отправлено.

Функция ``as_utc`` явно помечает «наивное» время как UTC — дальше клиент сам
приводит его к своему часовому поясу. Колонки со ``timezone=True`` (основная
часть схемы) уже приходят с ``+00:00`` и не меняются.
"""

from datetime import datetime, timezone


def as_utc(value: datetime | None) -> datetime | None:
    """Возвращает время с явным смещением UTC (``None`` — как есть)."""
    if value is None:
        return None
    if value.tzinfo is not None:
        return value
    return value.replace(tzinfo=timezone.utc)
