"""Правило приватности присутствия в одном месте.

Показывать присутствие («в сети» и «был(а) …») человек не обязан: настройка
``user.presence_hidden`` скрывает его от остальных. Настройка односторонняя (как
в WhatsApp): своё человек скрывает, а чужое видит как раньше — поэтому контекст
зрителя здесь не нужен.

Забыть это правило легко, а стоит дорого: время последней активности вылезет
там, где человек его сознательно спрятал — список чатов, участники, карточка
группы, контакты, поиск людей, история звонков и снимок присутствия по WS.
Поэтому проверка живёт здесь, а не расползается копиями по эндпоинтам.
"""

from typing import Any


def scrub_last_seen(payload: dict[str, Any], user: Any) -> dict[str, Any]:
    """Убирает присутствие из готового ответа, если человек его скрыл.

    Меняем именно словарь ответа: на самой модели ``last_seen`` подменять
    нельзя — SQLAlchemy счёл бы поле изменённым и записал NULL в БД.
    """
    if getattr(user, "presence_hidden", False):
        payload["last_seen"] = None
    return payload


__all__ = ("scrub_last_seen",)
