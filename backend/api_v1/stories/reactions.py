"""Набор реакций на истории — один список правды.

Зачем отдельный модуль: набор эмодзи нужен в двух местах — при валидации
входящего запроса и при отдаче клиенту (лента возвращает ``reaction_kinds``,
чтобы фронтенд рисовал панель по данным сервера и списки не разъезжались).

Ограничение набора (а не «любой эмодзи») даёт три вещи: в БД не окажется
произвольной строки, панель реакций выглядит одинаково у всех, а фильтр по
эмодзи остаётся простым.
"""

#: Допустимые реакции. Порядок = порядок кнопок в интерфейсе: сначала самые
#: ходовые (сердце, огонь, смех), затем остальные.
STORY_REACTION_KINDS: tuple[str, ...] = (
    "❤️",
    "🔥",
    "😂",
    "😮",
    "😢",
    "👏",
    "🙏",
    "👍",
    "💯",
    "🎉",
    "🤔",
    "🥰",
)

#: Как быстро отвечать на панель в интерфейсе: сколько кнопок показывать сразу,
#: остальные — под «ещё». Значение отдаётся клиенту вместе с лентой.
STORY_REACTIONS_PRIMARY = 5


def is_allowed_reaction(emoji: str) -> bool:
    """Входит ли эмодзи в разрешённый набор."""
    return emoji in STORY_REACTION_KINDS
