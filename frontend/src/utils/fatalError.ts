/**
 * Фатальные ошибки приложения: белый экран превращаем в понятное сообщение.
 *
 * Задача — не «упасть молча»: если рендер/обработчик упал и приложение не может
 * продолжать, показываем экран с перезагрузкой (см.
 * `components/common/FatalErrorScreen.vue`). Ошибки запросов сюда НЕ попадают:
 * их разбирает интерфейс (плашка «нет сети», повтор, понятные тексты).
 */

import { ref } from 'vue'

import { t } from '@/i18n'

/** Текст последней фатальной ошибки (пусто — всё в порядке). */
export const fatalError = ref('')

/** Сколько раз за сессию уже показывали экран — защита от «мигания» на цикле. */
let shown = 0

const MAX_SHOWS = 3

/**
 * Показывает экран фатальной ошибки.
 *
 * Повторные вызовы обновляют текст. После нескольких показов подряд молчим:
 * если ошибка возникает на каждое действие, полноэкранный оверлей превратился
 * бы в постоянный фон — в консоли она всё равно остаётся.
 */
export const reportFatalError = (error: unknown): void => {
  const message = error instanceof Error ? error.message : String(error ?? '')
  if (shown >= MAX_SHOWS) {
    console.warn(t('FatalError: сообщение не показано (лимит показов)'), message)
    return
  }
  shown += 1
  fatalError.value = message || t('Неизвестная ошибка')
}

/** Скрывает экран ошибки (пользователь решил продолжить работу). */
export const clearFatalError = (): void => {
  fatalError.value = ''
}
