import type { CallKind } from '@/stores/call'

/**
 * Каким должен стать звонок после того, как пользователь остановил показ экрана.
 *
 * Видеозвонок возвращается к камере (она была включена до показа), аудиозвонок
 * остаётся аудио: камеру ему включать нельзя — это было бы неожиданно и
 * выключить её в аудио-интерфейсе негде (кнопки камеры там нет).
 */
export function kindAfterScreenShare(before: CallKind): CallKind {
  return before === 'video' ? 'video' : 'audio'
}
