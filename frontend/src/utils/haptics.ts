/**
 * Короткая вибрация-отклик на действия в интерфейсе.
 *
 * На телефоне тактильный отклик заметно улучшает ощущение от жестов
 * (удержание сообщения, свайп-ответ, отправка): пользователь понимает, что
 * действие распознано, не глядя на экран. В браузерах без Vibration API
 * (iOS/Safari, десктоп) вызовы просто ничего не делают.
 */

/** Легкий «отклик» на тап/жест. */
export const HAPTIC_TAP = 12
/** Удержание: чуть заметнее тапа. */
export const HAPTIC_HOLD = 18

/**
 * Вибрация заданной длительности/шаблона (мс).
 *
 * Настройки приватности браузера и отсутствие API не считаем ошибкой: молча
 * ничего не вибрируем.
 */
export function haptic(pattern: number | number[] = HAPTIC_TAP): void {
  try {
    if (typeof navigator === 'undefined' || !('vibrate' in navigator)) return
    navigator.vibrate(pattern)
  } catch {
    /* нет доступа к вибрации — просто без отклика */
  }
}
