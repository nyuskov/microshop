/**
 * Названия, которые в браузере звучат официально-длинно, а в интерфейсе
 * привычнее короткая форма. Правим точечно: остальные 250+ названий браузер
 * знает сам и переводит на любой язык.
 */
const RU_SHORT_NAMES: Record<string, string> = {
  US: 'США',
  KR: 'Южная Корея'
}

/** Название страны на языке интерфейса (падать не должен никогда). */
export const countryName = (code: string, locale: string): string => {
  if (locale.startsWith('ru') && RU_SHORT_NAMES[code]) return RU_SHORT_NAMES[code]
  try {
    const display = new Intl.DisplayNames([locale], { type: 'region' })
    return display.of(code) ?? code
  } catch {
    // Старый движок без Intl.DisplayNames или неизвестный код — показываем код.
    return code
  }
}

/**
 * Варианты для выпадающего списка: название на языке интерфейса + код.
 *
 * Дополнительно к подписи кладём ключевые слова для поиска — код страны и её
 * английское название: подпись локализована («Казахстан»), а человек в списке из
 * 249 стран часто набирает «kz» или «kazakhstan», и без этого поиск выглядел бы
 * сломанным.
 */
export const countryOptions = (
  locale: string
): Array<{ value: string; label: string; keywords: readonly string[] }> =>
  COUNTRY_CODES.map((code) => ({
    value: code,
    label: countryName(code, locale),
    keywords: [code, countryName(code, 'en')]
  })).sort((left, right) => left.label.localeCompare(right.label, locale))
