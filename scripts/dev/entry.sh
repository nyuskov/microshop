#!/usr/bin/env bash
# Полный перезапуск стека с сохранением данных через дамп.
# 1) Перед сбросом снимается дамп текущей БД в ./db_dump — данные не теряются.
# 2) down -v --rmi all (volume БД удаляется).
# 3) build + up. Так как volume БД теперь пуст, контейнер db при инициализации
#    автоматически восстановит данные из ./db_dump/microshop_latest.sql.
# 4) Когда работа закончена (Ctrl+C или штатный выход `up`), стек гасится:
#    контейнеры удаляются, чтобы в докере не оставалось ничего работающего.
#    Тома и образы при этом НЕ удаляем: в томе БД — данные этой сессии, в
#    образах — кеш сборки; полностью они удаляются шагом 2 следующего запуска
#    (дамп сессии снимет шаг 1, он же поднимет db, если та погашена).
#
# Запуск из корня репозитория:  ./scripts/dev/entry.sh
set -euo pipefail
cd "$(dirname "$0")/../.."

# Гашение в конце: и при Ctrl+C во время `up`, и при обычном выходе.
# Флаг не даёт отработать дважды (INT-трап, затем EXIT-трап).
CLEANED=0
cleanup() {
    [[ "$CLEANED" -eq 1 ]] && return
    CLEANED=1
    echo
    echo "=== 5/5. Гашу и удаляю контейнеры (down --remove-orphans) ==="
    docker compose down --remove-orphans
}
trap cleanup EXIT INT TERM

echo "=== 1/4. Сохраняю дамп текущей БД ==="
./scripts/db/dump_db.sh

echo "=== 2/4. Полный сброс стека (down -v --rmi all) ==="
docker compose down -v --rmi all

echo "=== 3/4. Сборка образов ==="
docker compose build

echo "=== 4/4. Запуск (данные восстановятся из дампа) ==="
docker compose up
